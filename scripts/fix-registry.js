import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const DATA_DIR = path.join(__dirname, '../src/data/gesp');
const INDEX_FILE = path.join(DATA_DIR, 'index.js');

const levels = ['level1', 'level2', 'level3', 'level4', 'level5', 'level6', 'level7', 'level8'];

const isHistoricalPlaceholderFile = (fullPath) => {
    const content = fs.readFileSync(fullPath, 'utf-8');
    return content.includes('isHistoricalPlaceholder: true');
};

let importLines = [
    `// Central Registry for GESP Exam Papers`,
    `// AUTO-GENERATED BY scripts/fix-registry.js\n`
];

let registryLines = [
    `export const paperRegistry = {`
];

levels.forEach((level) => {
    const dirPath = path.join(DATA_DIR, level);
    if (!fs.existsSync(dirPath)) return;
    
    importLines.push(`// ========== ${level.replace('level', 'Level ')} ==========`);
    registryLines.push(`    // ===== ${level.replace('level', 'Level ')} =====`);
    
    const files = fs.readdirSync(dirPath)
        .filter(f => /^\d{4}-\d{2}-l\d\.js$/.test(f))
        .filter(f => !isHistoricalPlaceholderFile(path.join(dirPath, f)))
        .sort();

    files.forEach(file => {
        const id = file.replace('.js', '');
        // Create an import name like p202303l1
        const importName = 'p' + id.replace(/-/g, '');
        importLines.push(`import { paperData as ${importName} } from './${level}/${id}.js';`);
        registryLines.push(`    '${id}': ${importName},`);
    });
    importLines.push('');
});

registryLines.push(`};`);
registryLines.push(``);
registryLines.push(`export default paperRegistry;`);

const finalContent = importLines.join('\n') + '\n' + registryLines.join('\n') + '\n';
fs.writeFileSync(INDEX_FILE, finalContent, 'utf-8');
console.log('Successfully rebuilt src/data/gesp/index.js');
