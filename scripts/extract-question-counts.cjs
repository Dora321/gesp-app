/**
 * 提取所有试卷的题目数量，输出到 src/data/gesp/questionCounts.js
 * 
 * 用法：node scripts/extract-question-counts.cjs
 * 
 * 处理方式：逐个文件读取文本 → 解析计算题目数（避免 ESM import 的路径问题）
 */

const fs = require('fs');
const path = require('path');

const DATA_DIR = path.resolve(__dirname, '../src/data/gesp');
const LEVELS = ['level1', 'level2', 'level3', 'level4', 'level5', 'level6', 'level7', 'level8'];
const OUTPUT_FILE = path.resolve(DATA_DIR, 'questionCounts.js');

/**
 * 找到文件中键名对应的数组块内容（从 [ 到匹配的 ]）
 * 使用括号计数，正确处理嵌套 [] 和字符串/模板字面量中的括号
 */
function extractArrayBlock(content, startPos) {
  let i = startPos;
  let depth = 0;
  let inTemplate = false;
  let inSingleQuote = false;
  let inDoubleQuote = false;

  while (i < content.length) {
    const ch = content[i];
    const prev = i > 0 ? content[i - 1] : '';

    // Track string/template states
    if (ch === '`' && prev !== '\\' && !inSingleQuote && !inDoubleQuote) {
      inTemplate = !inTemplate;
    } else if (ch === "'" && prev !== '\\' && !inTemplate && !inDoubleQuote) {
      inSingleQuote = !inSingleQuote;
    } else if (ch === '"' && prev !== '\\' && !inTemplate && !inSingleQuote) {
      inDoubleQuote = !inDoubleQuote;
    }

    if (!inTemplate && !inSingleQuote && !inDoubleQuote) {
      if (ch === '[') depth++;
      else if (ch === ']') {
        depth--;
        if (depth === 0) {
          return content.substring(startPos, i + 1);
        }
      }
    }
    i++;
  }
  // If we never close, just return from start to end
  return content.substring(startPos);
}

/**
 * 从文本块中统计题目对象数量
 * 题目对象的特征：以 { 开头（独立或在新行），紧跟 id: 字段
 */
function countQuestionObjects(block) {
  const matches = block.match(/{\s*(?:\/\/[^\n]*\n\s*)*id:/g);
  return matches ? matches.length : 0;
}

/**
 * 从试卷文件文本中提取题目数量
 * 找到 paperData 对象中的 questions/programmingQuestions/codingQuestions 数组并计数
 */
function countQuestionsFromText(fileContent) {
  let totalCount = 0;

  for (const key of ['questions', 'programmingQuestions', 'codingQuestions']) {
    const keyPattern = new RegExp(`${key}\\s*:\\s*\\[`, 'g');
    let match;
    while ((match = keyPattern.exec(fileContent)) !== null) {
      const block = extractArrayBlock(fileContent, match.index + match[0].length - 1);
      totalCount += countQuestionObjects(block);
    }
  }

  return totalCount;
}

/**
 * 从文件名中提取 paperId
 * 例如：'2023-03-l1.js' → '2023-03-l1'
 */
function extractPaperId(filename) {
  return filename.replace(/\.js$/, '');
}

const counts = {};
let totalFiles = 0;
let errors = [];

for (const level of LEVELS) {
  const levelDir = path.join(DATA_DIR, level);
  if (!fs.existsSync(levelDir)) {
    console.warn(`Warning: Directory not found: ${levelDir}`);
    continue;
  }

  const files = fs.readdirSync(levelDir).filter(f => {
    return f.endsWith('.js') && f !== 'shared.js' && /^\d{4}-\d{2}-l\d\.js$/.test(f);
  });

  for (const file of files) {
    totalFiles++;
    const filePath = path.join(levelDir, file);
    try {
      const content = fs.readFileSync(filePath, 'utf-8');
      const paperId = extractPaperId(file);
      const questionCount = countQuestionsFromText(content);
      counts[paperId] = questionCount;
      console.log(`  ${paperId}: ${questionCount} 题`);
    } catch (e) {
      errors.push(`${file}: ${e.message}`);
      console.error(`  Error: ${file} - ${e.message}`);
    }
  }
}

// 输出 JS 文件
const output = `// Auto-generated by scripts/extract-question-counts.cjs
// DO NOT EDIT MANUALLY — regenerate with: node scripts/extract-question-counts.cjs

export const paperQuestionCounts = {
${Object.entries(counts)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, count]) => `  '${id}': ${count},`)
  .join('\n')}
};

export default paperQuestionCounts;
`;

fs.writeFileSync(OUTPUT_FILE, output, 'utf-8');
console.log(`\nDone: ${totalFiles} files processed, ${Object.keys(counts).length} papers with counts, ${errors.length} errors`);
console.log(`Output: ${OUTPUT_FILE}`);

if (errors.length > 0) {
  console.log('\nErrors:');
  errors.forEach(e => console.log(`  - ${e}`));
}