import { chromium } from 'playwright';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import assert from 'node:assert/strict';
import { createClassroomServer } from '../server/classroom.mjs';

const directory = mkdtempSync(join(tmpdir(), 'classroom-ui-'));
const server = createClassroomServer({ directory, adminPassword: 'ui-test-teacher', secure: false, fetchAI: async () => new Response('data: {"choices":[{"delta":{"content":"循环可以重复执行一段代码。"}}]}\n\ndata: [DONE]\n\n') });
server.listen(0, '127.0.0.1'); await once(server, 'listening');
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true });
mkdirSync('screenshots', { recursive: true });
try {
  const teacher = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
  await teacher.goto(`${base}/classroom-admin`);
  await teacher.getByLabel('教师密码').fill('ui-test-teacher');
  await teacher.getByRole('button', { name: '进入设置' }).click();
  await teacher.locator('#key').fill('sk-ui-mock-not-real');
  await teacher.getByRole('button', { name: '保存密钥' }).click();
  await teacher.getByText('密钥已保存，仅由后端使用。').waitFor();
  await teacher.getByRole('button', { name: '开启课堂' }).click();
  await teacher.locator('#live').waitFor({ state: 'visible' });
  const code = await teacher.locator('#code').textContent();
  await teacher.screenshot({ path: resolve('screenshots/classroom-admin.png'), fullPage: true });
  const student = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; student.on('pageerror', e => errors.push(e.message));
  await student.goto(`${base}/gesp-app/`);
  await student.getByRole('button', { name: '打开 AI 问答助手' }).first().click();
  await student.getByRole('button', { name: '输入课堂口令', exact: true }).click();
  await student.getByLabel('课堂口令', { exact: true }).fill(code);
  await student.getByRole('button', { name: '激活课堂', exact: true }).click();
  const input = student.getByPlaceholder('输入你的问题…（Enter 发送，Shift+Enter 换行）');
  await input.fill('什么是循环？'); await input.press('Enter');
  await student.getByText('循环可以重复执行一段代码。', { exact: true }).waitFor();
  await student.getByText(/全班剩余 499 次/).waitFor();
  await student.screenshot({ path: resolve('screenshots/classroom-student.png'), fullPage: true });
  assert.equal(await student.evaluate(() => document.cookie.includes('classroom_session')), false);
  await student.reload();
  await student.getByRole('button', { name: '打开 AI 问答助手' }).first().click();
  await student.getByText(/全班剩余 499 次/).waitFor();
  await student.setViewportSize({ width: 390, height: 844 });
  await student.reload();
  await student.getByRole('button', { name: '打开 AI 问答助手' }).first().click();
  await student.getByText(/全班剩余 499 次/).waitFor();
  await student.screenshot({ path: resolve('screenshots/classroom-mobile.png'), animations: 'disabled' });
  const composer = await input.boundingBox();
  assert.ok(composer.y + composer.height <= 844, 'Mobile composer must stay inside the viewport');
  teacher.on('dialog', d => d.accept());
  await teacher.getByRole('button', { name: '换一个', exact: true }).click();
  await teacher.waitForFunction(old => document.getElementById('code').textContent !== old, code);
  await input.fill('旧授权还有效吗？'); await input.press('Enter');
  await student.getByText(/课堂已结束或口令已更换/).waitFor();
  assert.deepEqual(errors, []);
  console.log('UI PASS: teacher setup, student activation, streamed answer, shared quota, refresh, mobile, rotation rejection. Mock AI only.');
} finally {
  await browser.close();
  await new Promise(done => server.close(done));
  rmSync(directory, { recursive: true, force: true });
}
