// 每条样例同时用于学生本机验收和 C++ 参考程序回归验证。
const referenceCode = (code, helpers) => {
  const source = `${helpers}\n${code}`;
  const headers = ['iostream'];
  for (const [header, pattern] of [
    ['iomanip', /setprecision/], ['string', /\bstring\b/], ['vector', /\bvector\b/],
    ['cstdlib', /\b(abs|rand|srand)\b/],
    ['algorithm', /\b(sort|stable_sort|reverse|max|min|max_element|count)\b/],
    ['queue', /\bqueue\b/], ['functional', /\bfunction\b/], ['utility', /\b(pair|swap)\b/],
  ]) {
    if (pattern.test(source)) headers.push(header);
  }
  return `${headers.map(header => `#include <${header}>`).join('\n')}\nusing namespace std;\n\n${helpers ? `${helpers}\n\n` : ''}int main() {\n${code}\n    return 0;\n}\n`;
};

const exercise = (level, lesson, title, focus, statement, input, output, samples, hint, boundary, code, helpers = '') => ({
  id: `cpp-${level}-${lesson}`, level, lesson, title, focus, statement, input, output,
  samples: samples.map(([input, output]) => ({ input, output })), hint, boundary,
  referenceCode: referenceCode(code, helpers),
});

