export function isMetaTag(tag) {
    return META_TAG.test(String(tag || '').trim());
}

export function normalizeTopicTags(tags) {
    const normalized = new Set();
    for (const rawTag of tags || []) {
        const tag = String(rawTag || '').trim();
        if (!tag || isMetaTag(tag)) continue;
        const canonical = ALIASES[tag] || [tag];
        for (const item of canonical) normalized.add(item);
    }
    return [...normalized];
}

export function getTopicGroup(tag) {
    return GROUP_BY_TAG.get(tag) || '其他考点';
}

