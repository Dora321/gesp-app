/** 规则表覆盖到的规范考点，供分组完整性测试使用。 */
export const INFERRED_TOPIC_TAGS = INFERENCE_RULES.map(([tag]) => tag);

/**
 * 从题面推断考点。仅供 topics.js 在一道题没有任何人工知识点标签时兜底使用。
 * 返回的标签已是规范名，不需要再过 ALIASES。
 */
// 题面是从官方 PDF 提取的，混进了康熙部首字符：`贪⼼` 的 `⼼` 是 U+2F3C，不是
// U+5FC3 的 `心`，`⾏`/`⽹`/`⼿` 同理。肉眼看不出差别，正则却全都匹配不上。
// NFKC 会把这些兼容字符折叠回常规汉字。
const normalize = (value) => String(value || '').normalize('NFKC');

export function inferTopicTags(question) {
    const stem = normalize(question?.question);
    const code = `${stem}\n${normalize(question?.code)}`;
    const any = `${code}\n${(question?.options || []).map(normalize).join('\n')}`;
    const scopes = { stem, code, any };

    const tags = new Set();
    for (const [tag, scope, pattern] of INFERENCE_RULES) {
        if (pattern.test(scopes[scope])) tags.add(tag);
    }
    return [...tags];
}
